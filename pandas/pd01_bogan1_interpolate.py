"""
결측치 처리
1. 삭제 - 행 또는 열 전체를 삭제 / drop으로 삭제 했었음
2. 임의의 값
    - 0 : fillna / 모르는 값을 0으로 처리
    - 평균 : mean / 평균값을 넣는다, 이상치(너무 큰값)가 문제다
    - 중위 : median / 중간값을 사용, 이것도 이상치
    - 앞값 : ffill / 앞에 값 가져오는거
    - 뒷값 : bfill / 뒤에 값 가져오는거
    - 특정값 : 조건 보고 직접 넣는다
    - 최빈값 : most_frequent / 최빈값(가장 자주 나타나는 값)
    - 기타등등... (랜덤...) / 권하지 않는다
3. interpolate - 보간 (알려진 데이터 점 집합의 범위 내에 새 데이터 점을 추가하는 기법)
4. 모델 : .predict(값을 예측해서), (전혀 다른 모델 사용해야 과적합이 안됨)
5. 부스팅(트리) 계열 모델 : 통상 결측치, 이상치에 대해 영향을 덜 받는다.(자유롭다) / XG부스터 돌리면 이상치 처리 안해도된다
6. 스케일링 (로브스트등...) / 이상치에 자유로움, 결측치는 따로 해줘야함
"""

import pandas as pd
import numpy as np

dataes = [
    '11/11/2026', '12/11/2026', '13/11/2026',
    '14/11/2026', '15/11/2026', '16/11/2026',
    '17/11/2026', '18/11/2026', '19/11/2026',
]
# 판다스에서 제공하는 데이트 타입의 형태 / 인덱스로 사용할꺼다
dataes = pd.to_datetime(dataes, dayfirst=True) 
# print(dataes)

#['11/11/2026', '12/11/2026', '13/11/2026', '14/11/2026', '15/11/2026', '16/11/2026', '17/11/2026', '18/11/2026', '19/11/2026']

print("================================")
ts = pd.Series([0, 2, np.nan, np.nan, 8, 10, np.nan, 14, np.nan], index=dataes)
# 여기서 날짜는 데이터가 아니라 인덱스 이다 / 데이터화 시켜서 할 수 있지만 지금은 인덱스일 뿐인다
print(ts)

print("================================")
# 판다스에서 보통 세팅이 되어 있다
ts = ts.interpolate() # 이렇게 하면 끝!
print(ts)

# 중간값들은 linear로 채워짐
# interpolate의 마지막 결측치 값은 ffill (이전값으로 채워짐)
# interpolate의 처음 결측치는 nan으로 채워짐



